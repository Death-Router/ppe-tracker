"""Значения, зафиксированные Положением об обеспечении СИЗ ПАО «Ростелеком».

Источник — форма личной карточки учёта выдачи СИЗ (приложение № 4 к
Положению, редакция 2, приказ 01/01/4523/24 от 13.02.2025) и примечания
к ней: «размеры и рост прописываем согласно размерных сеток, межразмерность
будет считаться ошибкой».
"""

# Рост по размерным сеткам Положения. Значения вне списка означают, что
# человек попал между размерами, — по Положению это ошибка, а не вариант.
HEIGHT_GRID: tuple[str, ...] = (
    "158-164",
    "170-176",
    "182-188",
    "194-200",
    "206-212",
)

# Способ выдачи дерматологических СИЗ (графа 5 оборотной стороны карточки).
# Для остальных СИЗ графа не заполняется — там всегда «лично».
ISSUE_METHODS: tuple[str, ...] = ("лично", "дозатор")


def is_height_from_grid(value: str) -> bool:
    """Проверяет, что рост указан диапазоном из сетки, а не «примерно»."""
    return value.strip() in HEIGHT_GRID


def height_error_message(value: str) -> str:
    """Текст ошибки для роста вне сетки.

    Возвращается строкой, а не валидатором Pydantic: ответ 422 с массивом
    ошибок клиент показывает как «HTTP 422», а не как объяснение.
    """
    return (
        f"Рост «{value.strip()}» не из размерной сетки. "
        f"Допустимые значения: {', '.join(HEIGHT_GRID)}. "
        "Межразмерность считается ошибкой."
    )
