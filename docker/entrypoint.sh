#!/bin/sh
# Точка входа прод-образа.
#
# Миграции по умолчанию НЕ применяются: схема с нуля сейчас не собирается
# (PROJECT.md, ловушка 8 — обрыв в цепочке миграций). Включайте AUTO_MIGRATE=1
# только на базе, которая уже приведена к голове; иначе контейнер упадёт на
# старте и будет перезапускаться, а причина будет неочевидна.
set -e

if [ "${AUTO_MIGRATE:-0}" = "1" ]; then
    attempt=1
    while [ "$attempt" -le 30 ]; do
        if alembic upgrade head; then
            echo "миграции применены (попытка $attempt)"
            break
        fi
        echo "миграции не прошли (попытка $attempt), ждём базу 2 с"
        attempt=$((attempt + 1))
        sleep 2
    done

    if [ "$attempt" -gt 30 ]; then
        echo "не удалось применить миграции: база не готова или цепочка порвана" >&2
        exit 1
    fi
fi

exec "$@"
